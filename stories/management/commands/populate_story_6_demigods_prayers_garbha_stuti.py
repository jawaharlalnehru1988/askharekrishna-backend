class Command(BaseCommand):
    help = 'Populate Story 6: The Demigods’ Transcendental Prayers (Garbha-stuti) across all 7 languages'

    def handle(self, *args, **options):
        topic = StoryMainTopic.objects.get(id=2)
        slug = 'krishna-pastimes-the-demigods-transcendental-prayers-garbha-stuti'
        image_path = 'stories/images/demigods_garbha_stuti.jpg'

        story, created = Story.objects.get_or_create(
            slug=slug,
            defaults={
                'topic': topic,
                'order': 5,
                'imagePath': image_path,
            }
        )
        if not created:
            story.topic = topic
            story.order = 5
            story.imagePath = image_path
            story.save()

        articles = {
            'en': ('Krishna Pastimes', "The Demigods' Transcendental Prayers (Garbha-stuti)", ARTICLE_EN),
            'ta': ('கிருஷ்ண லீலைகள்', "தேவர்களின் திவ்ய கர்ப்ப ஸ்துதி பிரார்த்தனைகள்", ARTICLE_TA),
            'hi': ('श्रीकृष्ण की दिव्य लीलाएँ', "देवताओं की दिव्य गर्भ-स्तुति", ARTICLE_HI),
            'ml': ('ശ്രീകൃഷ്ണ ലീലകൾ', "ദേവന്മാരുടെ ദിവ്യമായ ഗർഭസ്തുതി", ARTICLE_ML),
            'bn': ('শ্রীকৃষ্ণের দিব্য লীলা', "দেবতাদের দিব্য গর্ভ-স্তুতি", ARTICLE_BN),
            'te': ('శ్రీకృష్ణుని దివ్య లీలలు', "దేవతల దివ్య గర్భ-స్తుతి", ARTICLE_TE),
            'kn': ('ಶ್ರೀಕೃಷ್ಣ ಲೀಲೆಗಳು', "ದೇವತೆಗಳ ದಿವ್ಯ ಗರ್ಭ-ಸ್ತುತಿ", ARTICLE_KN),
        }

        created_trans = {}
        for lang, (main_topic, sub_topic, text) in articles.items():
            tr, _ = StoryTranslation.objects.get_or_create(
                story=story,
                language_code=lang,
                defaults={
                    'mainTopic': main_topic,
                    'subTopic': sub_topic,
                    'article': text,
                }
            )
            tr.mainTopic = main_topic
            tr.subTopic = sub_topic
            tr.article = text
            tr.save()
            created_trans[lang] = tr
            self.stdout.write(f"Saved {lang} translation.")

        # Save questions across all 7 languages
        for idx, q_data in enumerate(QUESTIONS_DATA, start=1):
            for lang in ['en', 'ta', 'hi', 'ml', 'bn', 'te', 'kn']:
                tr = created_trans[lang]
                q_text, opts = q_data[lang]

                q, _ = StoryQuestion.objects.get_or_create(
                    translation=tr,
                    order=idx,
                    defaults={'question_text': q_text}
                )
                q.question_text = q_text
                q.save()

                q.options.all().delete()
                for opt_idx, (opt_text, is_corr) in enumerate(opts, start=1):
                    StoryQuestionOption.objects.create(
                        question=q,
                        order=opt_idx,
                        option_text=opt_text,
                        is_correct=is_corr
                    )

        self.stdout.write(self.style.SUCCESS(f"Successfully populated Story 6 (ID: {story.id}) across all 7 languages with 10 MCQs each!"))
