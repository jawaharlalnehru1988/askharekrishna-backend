class Command(BaseCommand):
    help = 'Add Malayalam and Bengali translations and questions to Story 241'

    def handle(self, *args, **options):
        story = Story.objects.get(id=241)

        # Malayalam
        tr_ml, _ = StoryTranslation.objects.get_or_create(
            story=story,
            language_code='ml',
            defaults={
                'mainTopic': 'ശ്രീകൃഷ്ണ ലീലകൾ',
                'subTopic': 'രാജകീയ വിവാഹവും കംസന്റെ ഉഗ്രക്രോധവും',
                'article': ARTICLE_241_ML,
            }
        )
        tr_ml.mainTopic = 'ശ്രീകൃഷ്ണ ലീലകൾ'
        tr_ml.subTopic = 'രാജകീയ വിവാഹവും കംസന്റെ ഉഗ്രക്രോധവും'
        tr_ml.article = ARTICLE_241_ML
        tr_ml.save()

        tr_ml.questions.all().delete()
        for idx, (q_text, opts) in enumerate(ML_QUESTIONS, start=1):
            q = StoryQuestion.objects.create(
                translation=tr_ml,
                order=idx,
                question_text=q_text
            )
            for opt_idx, (opt_text, is_corr) in enumerate(opts, start=1):
                StoryQuestionOption.objects.create(
                    question=q,
                    order=opt_idx,
                    option_text=opt_text,
                    is_correct=is_corr
                )
        self.stdout.write("Saved Malayalam translation and questions for Story 241.")

        # Bengali
        tr_bn, _ = StoryTranslation.objects.get_or_create(
            story=story,
            language_code='bn',
            defaults={
                'mainTopic': 'শ্রীকৃষ্ণের দিব্য লীলা',
                'subTopic': 'রাজকীয় বিবাহ ও কংসের ভয়ঙ্কর ক্রোধ',
                'article': ARTICLE_241_BN,
            }
        )
        tr_bn.mainTopic = 'শ্রীকৃষ্ণের দিব্য লীলা'
        tr_bn.subTopic = 'রাজকীয় বিবাহ ও কংসের ভয়ঙ্কর ক্রোধ'
        tr_bn.article = ARTICLE_241_BN
        tr_bn.save()

        tr_bn.questions.all().delete()
        for idx, (q_text, opts) in enumerate(BN_QUESTIONS, start=1):
            q = StoryQuestion.objects.create(
                translation=tr_bn,
                order=idx,
                question_text=q_text
            )
            for opt_idx, (opt_text, is_corr) in enumerate(opts, start=1):
                StoryQuestionOption.objects.create(
                    question=q,
                    order=opt_idx,
                    option_text=opt_text,
                    is_correct=is_corr
                )
        self.stdout.write("Saved Bengali translation and questions for Story 241.")

        self.stdout.write(self.style.SUCCESS("Successfully added Malayalam and Bengali to Story 241!"))
